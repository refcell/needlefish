//! Renders the files `base devnet init` writes into `.devnet/`. Pure: the caller
//! supplies the timestamp, genesis hashes, and JWT bytes, and does the file IO.

const std = @import("std");
const assert = std.debug.assert;
const Writer = std.Io.Writer;
const genesis = @import("genesis.zig");
const accounts = @import("accounts.zig");

pub const Ports = struct {
    l1_http: u16 = 8545,
    l1_beacon: u16 = 5052,
    sequencer_http: u16 = 9545,
    sequencer_engine: u16 = 9551,
    sequencer_rpc: u16 = 7545,
    verifier_http: u16 = 10545,
    verifier_engine: u16 = 10551,
    verifier_rpc: u16 = 8547,
    batcher_metrics: u16 = 7300,
};

pub const File = enum {
    l1_genesis,
    l2_genesis,
    rollup,
    env,

    pub fn name(file: File) []const u8 {
        return switch (file) {
            .l1_genesis => "l1-genesis.json",
            .l2_genesis => "l2-genesis.json",
            .rollup => "rollup.json",
            .env => "devnet.env",
        };
    }
};

pub const jwt_file_name = "jwt.hex";

/// Renders `file` into `w`.
pub fn render(
    w: *Writer,
    file: File,
    config: *const genesis.Config,
    anchor: genesis.GenesisAnchor,
    ports: Ports,
) Writer.Error!void {
    switch (file) {
        .l1_genesis => try genesis.write_l1_genesis(w, config),
        .l2_genesis => try genesis.write_l2_genesis(w, config),
        .rollup => try genesis.write_rollup_config(w, config, anchor),
        .env => try write_env(w, config, ports),
    }
}

/// Shell-sourceable summary for scripts and the smoke test. No secrets.
pub fn write_env(w: *Writer, config: *const genesis.Config, ports: Ports) Writer.Error!void {
    try w.writeAll("# Generated by `base devnet init`. Public devnet values only.\n");
    try w.print("GENESIS_TIMESTAMP={d}\n", .{config.genesis_timestamp});
    try w.print("L1_CHAIN_ID={d}\nL2_CHAIN_ID={d}\n", .{ config.l1_chain_id, config.l2_chain_id });
    // L2 blocks come every L2_BLOCK_TIME_MS (Denim at genesis); L2_BLOCK_TIME is the
    // rollup config's legacy pre-Denim block time.
    try w.print("L1_BLOCK_TIME={d}\nL2_BLOCK_TIME={d}\nL2_BLOCK_TIME_MS={d}\n", .{
        config.l1_block_time_s,
        config.l2_block_time_s,
        genesis.l2_block_interval_ms,
    });
    inline for (@typeInfo(Ports).@"struct".field_names) |name| {
        var upper: [name.len]u8 = undefined;
        _ = std.ascii.upperString(&upper, name);
        try w.print("PORT_{s}={d}\n", .{ &upper, @field(ports, name) });
    }
    try w.print("BATCH_INBOX=0x{x}\n", .{&config.batch_inbox().bytes});
    try w.print("PORTAL=0x{x}\n", .{&genesis.portal_address.bytes});
    for (std.enums.values(accounts.Role)) |role| {
        const index = @backingInt(role);
        const account = accounts.derive_dev(index);
        var upper_buffer: [32]u8 = undefined;
        const upper = std.ascii.upperString(&upper_buffer, @tagName(role));
        try w.print("{s}_ADDRESS=0x{x}\n{s}_INDEX={d}\n", .{
            upper, &account.address.bytes, upper, index,
        });
    }
}

/// Hex text of a 32-byte JWT secret, as EL/CL `--jwt` flags expect.
pub fn jwt_hex(secret: [32]u8) [66]u8 {
    assert(!std.mem.allEqual(u8, &secret, 0));
    var out: [66]u8 = undefined;
    _ = std.fmt.bufPrint(&out, "0x{x}", .{&secret}) catch unreachable; // Exact size.
    assert(out[0] == '0' and out[1] == 'x');
    return out;
}

const testing = std.testing;

test "init: env has ports, roles, and no keys" {
    const config: genesis.Config = .{ .genesis_timestamp = 42 };
    var buffer: [4096]u8 = undefined;
    var w: Writer = .fixed(&buffer);
    try render(&w, .env, &config, .{ .l1_hash = @splat(0), .l2_hash = @splat(0) }, .{});
    const text = w.buffered();
    try testing.expect(std.mem.indexOf(u8, text, "GENESIS_TIMESTAMP=42\n") != null);
    try testing.expect(std.mem.indexOf(u8, text, "PORT_L1_HTTP=8545\n") != null);
    try testing.expect(std.mem.indexOf(u8, text, "BATCHER_INDEX=6\n") != null);
    try testing.expect(std.mem.indexOf(
        u8,
        text,
        "BATCHER_ADDRESS=0x976ea74026e726554db657fa54763abd0c3a0aa9\n",
    ) != null);
    try testing.expect(std.mem.indexOf(u8, text, "KEY") == null);
}

test "init: jwt hex" {
    const hex = jwt_hex(@splat(0xab));
    try testing.expectEqualStrings("0x", hex[0..2]);
    for (0..32) |i| try testing.expectEqualStrings("ab", hex[2 + 2 * i ..][0..2]);
}
