/// Decodes hex text that may contain newlines into the front of `buffer`.
pub fn decode(buffer: []u8, text: []const u8) []u8 {
    assert(buffer.len * 2 >= text.len / 2);
    var length: usize = 0;
    var high: ?u8 = null;
    for (text) |char| {
        if (char == '\n') continue;
        const nibble = std.fmt.charToDigit(char, 16) catch unreachable; // Vectors are hex.
        if (high) |value| {
            buffer[length] = value << 4 | nibble;
            length += 1;
            high = null;
        } else {
            high = nibble;
        }
    }
    assert(high == null);
    assert(length <= buffer.len);
    return buffer[0..length];
}
